
-- Создание базы данных
CREATE DATABASE IF NOT EXISTS Library;
USE Library;

-- Таблица: Книга (Номер, Название, Издательство, Год_издания, Количество_страниц)
CREATE TABLE IF NOT EXISTS Книга (
    Номер INT PRIMARY KEY,
    Название VARCHAR(255) NOT NULL,
    Издательство VARCHAR(255),
    Год_издания INT,
    Количество_страниц INT
);

-- Таблица: Автор (Номер, ФИО, Город_проживания)
CREATE TABLE IF NOT EXISTS Автор (
    Номер INT PRIMARY KEY,
    ФИО VARCHAR(255) NOT NULL,
    Город_проживания VARCHAR(255)
);

-- Таблица: Полка (Шифр, Название, Место_нахождения)
CREATE TABLE IF NOT EXISTS Полка (
    Шифр VARCHAR(50) PRIMARY KEY,
    Название VARCHAR(255) NOT NULL,
    Место_нахождения VARCHAR(255)
);

-- Таблица: Расстановка (Номер_книги, Номер_автора, Шифр_полки, Количество)
CREATE TABLE IF NOT EXISTS Расстановка (
    Номер_книги INT,
    Номер_автора INT,
    Шифр_полки VARCHAR(50),
    Количество INT,
    PRIMARY KEY (Номер_книги, Номер_автора, Шифр_полки),
    FOREIGN KEY (Номер_книги) REFERENCES Книга(Номер),
    FOREIGN KEY (Номер_автора) REFERENCES Автор(Номер),
    FOREIGN KEY (Шифр_полки) REFERENCES Полка(Шифр)
);

